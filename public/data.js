function makeTable(id, multi = true) {
  // 单命中模式下，表格 47 换成普通表格，只有表格 3 含目标数据。
  const fixed = target.find((table) => table.id === id && (multi || id !== 47));
  if (fixed) return fixed;
  const [name, unit, rowHeaders, colHeaders] = topics[(id * 7) % topics.length];
  const money = unit === "万元" || unit === "元";
  return {
    id,
    title: `${name}（${Math.ceil(id / 12)}）`,
    unit,
    rowHeaders,
    colHeaders,
    rows: rowHeaders.map((_, r) =>
      colHeaders.map((_, c) => {
        const n = ((id * 31 + r * 17 + c * 13) % 900) + 100;
        return money ? (n / 10).toFixed(2) : String(n);
      }),
    ),
  };
}
